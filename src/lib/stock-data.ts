/**
 * บล็อกนิยามเครื่องมือสำหรับฝังใน system prompt (The Professor)
 */
export function buildToolboxPromptBlock(): string {
  return TOOLBOX.map(
    (t, i) => `${i + 1}. ${t.name}\n   ${t.judgeDef}`
  ).join('\n\n');
}

/**
 * รายชื่อเครื่องมือแบบสั้น — ใช้ใน prompt ของกรรมการตัวอื่นที่ไม่ต้องรู้นิยามละเอียด
 */
export function buildToolboxNameList(): string {
  return TOOLBOX.map((t) => t.name).join(' · ');
}

