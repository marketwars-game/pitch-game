export const TOOL_COUNT = TOOLBOX.length;

/**
 * บล็อกนิยาม WHY สำหรับฝังใน system prompt (The Analyst)
 */
export function buildToolboxPromptBlock(): string {
  return TOOLBOX.map(
    (t, i) => `${i + 1}. ${t.name}\n   ${t.judgeDef}`
  ).join('\n\n');
}

/**
 * รายชื่อ WHY แบบสั้น — ใช้ใน prompt ของกรรมการตัวอื่นที่ไม่ต้องรู้นิยามละเอียด
 */
export function buildToolboxNameList(): string {
  return TOOLBOX.map((t) => t.name).join(' · ');
}

