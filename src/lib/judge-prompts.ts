/**
 * T9-v6: ล้าง "รูปแบบ" ออกจากข้อความก่อนส่งให้ The Analyst — เหลือแต่เนื้อหา
 * ไม่แตะตัวอักษรไทย/อังกฤษ/ตัวเลข/เครื่องหมายวรรคตอนปกติ
 */
export function cleanPitchForAnalyst(pitch: string): string {
  return (
    pitch
      // เศษโค้ดจากการ copy: ' + ขึ้นบรรทัด '   และ   " + ขึ้นบรรทัด "
      .replace(/['"`]\s*\+\s*\n?\s*['"`]/g, ' ')
      // markdown: ตัวหนา/เอียง/หัวข้อ/โค้ด
      .replace(/\*\*|__|~~|`+/g, '')
      .replace(/^\s{0,3}#{1,6}\s+/gm, '')
      // bullet และเลขข้อหน้าบรรทัด
      .replace(/^\s*(?:[-*•·▪◦–—]|\d{1,2}[.)])\s+/gm, '')
      // ขึ้นบรรทัด/ช่องว่างถี่ → ช่องว่างเดียว
      .replace(/\s*\n+\s*/g, ' ')
      .replace(/[ \t]{2,}/g, ' ')
      // เครื่องหมายคำพูด/จุลภาคที่ค้างหัว-ท้ายทั้งข้อความ
      .replace(/^['"`\s]+/, '')
      .replace(/['"`,;\s]+$/, '')
      .trim()
  );
}

/**
 * สร้าง user message จากเคส + ข้อความของผู้เล่น
 * T9-v6: ส่ง persona = 'analyst' → ข้อความถูกล้างรูปแบบก่อน · persona อื่นหรือไม่ส่ง = ข้อความดิบ
 */
export function buildUserMessage(
  caseData: CaseData,
  pitchRaw: string,
  persona?: PersonaKey
): string {
  const cleaned = persona === 'analyst' ? cleanPitchForAnalyst(pitchRaw) : pitchRaw;
  // กันกรณีล้างแล้วว่าง (ข้อความมีแต่เครื่องหมาย) — ใช้ของเดิม
  const pitch = cleaned.length > 0 ? cleaned : pitchRaw;

  const facts =
    caseData.facts && caseData.facts.length > 0
      ? caseData.facts.map((f) => `- ${f}`).join('\n')
      : '- (ไม่มีข้อมูลเพิ่มเติม)';

  const said =
    caseData.chat && caseData.chat.length > 0
      ? caseData.chat.map((c) => `"${c}"`).join('\n')
      : `"${caseData.headline}"`;

  return `เคส: ${caseData.name} อายุ ${caseData.age}
${facts}

สิ่งที่ ${caseData.name} พิมพ์มาในไลน์:
${said}

---

ข้อความที่ผู้เล่นพิมพ์ตอบ (ความยาว ${pitch.length} ตัวอักษร):
"""
${pitch}
"""

ใช้ tool submit_judgment เพื่อส่งคะแนนและคอมเมนต์`;
}
